"""Validate and import the supplied v2 neighborhood kit, preserving source PNGs."""
import argparse
import csv
import hashlib
from io import BytesIO, StringIO
from pathlib import Path, PurePosixPath
from zipfile import ZipFile

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def import_kit(path):
    target = ROOT / "Assets" / "Cenarios" / "Vizinhanca"
    with ZipFile(path) as archive:
        rows = list(csv.DictReader(StringIO(archive.read("07_documentacao/manifesto.csv").decode("utf-8-sig"))))
        if len(rows) != 50:
            raise ValueError("Expected exactly 50 sprite records.")
        ids = set()
        prepared = []
        for row in rows:
            relative = PurePosixPath(row["arquivo"])
            if relative.is_absolute() or ".." in relative.parts or "\\" in row["arquivo"]:
                raise ValueError(f"Invalid archive path: {relative}")
            if relative.suffix != ".png" or relative.stem in ids:
                raise ValueError(f"Invalid or duplicate sprite ID: {relative}")
            ids.add(relative.stem)
            raw = archive.read(row["arquivo"])
            image = Image.open(BytesIO(raw))
            pivot = (int(row["pivo_x"]), int(row["pivo_y"]))
            if image.mode != "RGBA" or image.size != (int(row["largura_px"]), int(row["altura_px"])):
                raise ValueError(f"Invalid dimensions or mode: {relative}")
            alpha = image.getchannel("A")
            if alpha.getextrema() != (0, 255) or not (0 <= pivot[0] < image.width and 0 <= pivot[1] < image.height):
                raise ValueError(f"Invalid alpha or pivot: {relative}")
            box = alpha.getbbox()
            if not box or min(box[:2]) <= 0 or box[2] >= image.width or box[3] >= image.height:
                raise ValueError(f"Clipped or empty sprite: {relative}")
            prepared.append((relative, raw, pivot, box))
        lines = ["# Generated by tools/import_vizinhanca.py; PNGs and pivots match the supplied manifest.",
                 "extends RefCounted", "", "const ITENS := {"]
        for relative, raw, pivot, box in prepared:
            destination = target.joinpath(*relative.parts)
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(raw)
            lines.extend([
                f'    "{relative.stem}": {{',
                f'        "textura": preload("res://Assets/Cenarios/Vizinhanca/{relative}"),',
                f'        "pivo": Vector2{pivot},',
                f'        "altura": {box[3] - box[1]},',
            ])
            if relative.parts[0] == "01_predios":
                # Landmarks for this geometric kit: the front starts 8px inside the roof.
                left_x = box[0] + 8
                right_x = 2 * pivot[0] - left_x
                left = (left_x, pivot[1] + (left_x - pivot[0]) * 20 / 64 + 3)
                right = (right_x, pivot[1] + (right_x - pivot[0]) * 20 / 64 + 3)
                back = (box[2] - 8, right[1] - (box[2] - 8 - right_x) / 2)
                lines.extend([f'        "frente": Vector2{left},', f'        "canto": Vector2{right},',
                              f'        "fundo": Vector2{back},'])
            lines.append("    },")
        lines.append("}")
        for name in ("manifesto.csv", "LEIA_ME.txt"):
            (target / name).write_bytes(archive.read("07_documentacao/" + name))
        (ROOT / "scripts" / "CatalogoVizinhanca.gd").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Imported {len(prepared)} unchanged PNGs; archive SHA256: {hashlib.sha256(path.read_bytes()).hexdigest()}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    import_kit(parser.parse_args().archive)
